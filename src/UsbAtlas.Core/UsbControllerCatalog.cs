using System.Text.Json;
using System.Text.Json.Serialization;

namespace UsbAtlas.Core;

/// <summary>Where a USB host controller sits, inferred from its pci.ids product name. Never a verified board fact.</summary>
public enum ControllerPlacement
{
    /// <summary>Integrated in the CPU or SoC package.</summary>
    CpuSoc,
    /// <summary>A separate chipset chip (PCH, southbridge) on the motherboard.</summary>
    Chipset,
    /// <summary>A chipset die that sits inside the CPU package, typical for mobile platforms.</summary>
    OnPackageChipset,
    /// <summary>A discrete Thunderbolt/USB controller chip on the board, an add-in card or a dock.</summary>
    DiscreteController
}

/// <param name="Confidence">"High" for entries named in pci.ids, "Medium" for IDs taken from secondary sources.</param>
/// <param name="Source">Where the ID and name come from.</param>
public sealed record ControllerCatalogEntry(string Id, string Name, ControllerPlacement Placement, string Confidence, string Source);

/// <summary>
/// Intel and AMD USB host controllers from the PCI ID Repository, each with a placement class.
/// Generated by tools/generate-controller-catalog.py; see the script for the classification rules.
/// </summary>
public sealed class UsbControllerCatalog
{
    private sealed record Document(string Source, string Url, string Version, ControllerCatalogEntry[] Entries);

    private static readonly JsonSerializerOptions Options = new()
    {
        PropertyNameCaseInsensitive = true,
        Converters = { new JsonStringEnumConverter() }
    };

    private readonly Dictionary<string, ControllerCatalogEntry> entries;

    public string Source { get; }
    public string Url { get; }
    public string Version { get; }
    public int Count => entries.Count;

    public UsbControllerCatalog()
    {
        using var stream = typeof(UsbControllerCatalog).Assembly.GetManifestResourceStream("UsbAtlas.Core.controller-catalog.json")
            ?? throw new InvalidDataException("The controller catalog resource is missing.");
        var document = JsonSerializer.Deserialize<Document>(stream, Options)
            ?? throw new InvalidDataException("The controller catalog is empty.");
        Source = document.Source;
        Url = document.Url;
        Version = document.Version;
        entries = document.Entries.ToDictionary(e => e.Id.ToUpperInvariant());
    }

    /// <summary>Looks up a controller by PCI vendor and device ID, case-insensitive. Null when the catalog has no entry.</summary>
    public ControllerCatalogEntry? Find(string? vendorId, string? deviceId)
    {
        if (string.IsNullOrWhiteSpace(vendorId) || string.IsNullOrWhiteSpace(deviceId)) return null;
        return entries.GetValueOrDefault($"{vendorId}:{deviceId}".ToUpperInvariant());
    }
}
